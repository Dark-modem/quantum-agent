// rollback.go — journal-driven rollback plus the generated standalone
// rollback script. The script is what the systemd timer runs: self-contained
// POSIX sh that re-runs the recorded inverse argvs and restores owned files
// from embedded previous bytes, so a rollback works even when the agent
// binary is dead, being upgraded, or was never re-armed.

package hardening

import (
	"context"
	"fmt"
	"os"
	"strconv"
	"strings"
)

// rollbackJournal walks a journal's steps in reverse and undoes every
// executed mutation: files first (within each step), then inverse argvs in
// reverse. The timer is disarmed first so a manual rollback cannot race the
// automatic one. Returns per-item error strings (empty = clean).
func rollbackJournal(ctx context.Context, j *Journal, reason string) []string {
	disarmRollbackTimer(ctx, j.TimerUnit)
	var errs []string
	for i := len(j.Steps) - 1; i >= 0; i-- {
		step := j.Steps[i]
		if step.Skipped {
			continue
		}
		for k := len(step.Files) - 1; k >= 0; k-- {
			f := step.Files[k]
			if f.Absent {
				if err := os.Remove(f.Path); err != nil && !os.IsNotExist(err) {
					errs = append(errs, fmt.Sprintf("remove %s: %v", f.Path, err))
				}
				continue
			}
			if err := writeFileAtomic(f.Path, f.Before, os.FileMode(f.Mode)); err != nil {
				errs = append(errs, fmt.Sprintf("restore %s: %v", f.Path, err))
			}
		}
		for k := len(step.Undo) - 1; k >= 0; k-- {
			cmd := step.Undo[k]
			if _, err := run(ctx, cmd[0], cmd[1:]...); err != nil {
				errs = append(errs, fmt.Sprintf("%v: %v", cmd, err))
			}
		}
	}
	j.Error = reason
	j.RolledBack = true
	_ = saveJournal(j)
	markJournalTerminal(j, ".rolledback")
	_ = os.Remove(rollbackScriptPath(j.ID))
	return errs
}

// writeRollbackScript renders the standalone rollback script for one
// journal: the undo entries for the (possibly not-yet-applied) risky items,
// followed by the undo of everything the journal already applied, then the
// terminal bookkeeping.
func writeRollbackScript(journalID string, planned []undoEntry) error {
	var b strings.Builder
	b.WriteString("#!/bin/sh\n")
	b.WriteString("# Generated by quantum-agent hardening for journal " + journalID + "\n")
	b.WriteString("# Fires ONLY via the armed systemd timer when the panel did not confirm.\n")
	b.WriteString("# Every line is idempotent and best-effort; output lands in the log.\n")
	b.WriteString("set -u\n")
	log := rollbackLogPath(journalID)
	b.WriteString("exec 2>>" + shQuote(log) + "\n")

	emit := func(e undoEntry) {
		for k := len(e.Files) - 1; k >= 0; k-- {
			f := e.Files[k]
			if f.Absent {
				b.WriteString("rm -f " + shQuote(f.Path) + "\n")
				continue
			}
			b.WriteString("cat > " + shQuote(f.Path) + " <<'QH_EOF'\n")
			b.WriteString(f.Before)
			if !strings.HasSuffix(f.Before, "\n") {
				b.WriteString("\n")
			}
			b.WriteString("QH_EOF\n")
			b.WriteString("chmod " + octal(f.Mode) + " " + shQuote(f.Path) + "\n")
		}
		for k := len(e.Cmds) - 1; k >= 0; k-- {
			b.WriteString(shLine(e.Cmds[k]) + " || echo \"undo failed: " + shQuote(shLine(e.Cmds[k])) + "\"\n")
		}
	}

	// Risky items planned but possibly not applied (reverse execution order).
	for i := len(planned) - 1; i >= 0; i-- {
		emit(planned[i])
	}
	// Steps already applied (phase 1 etc.), newest first.
	if j, err := LoadJournal(journalID); err == nil && j != nil {
		for i := len(j.Steps) - 1; i >= 0; i-- {
			step := j.Steps[i]
			if step.Skipped {
				continue
			}
			emit(undoEntry{Files: step.Files, Cmds: step.Undo})
		}
	}

	b.WriteString("mv -f " + shQuote(journalPath(journalID)) + " " + shQuote(journalPath(journalID)+".rolledback") + " 2>/dev/null || true\n")
	b.WriteString("rm -f " + shQuote(latestJournalPath()) + "\n")
	b.WriteString("echo \"rollback fired at \\$(date -Is)\" >> " + shQuote(log) + "\n")
	b.WriteString("exit 0\n")
	return writeFileAtomic(rollbackScriptPath(journalID), b.String(), 0o700)
}

func octal(m uint32) string {
	return "0" + strconv.FormatUint(uint64(m), 8)
}

// shQuote renders one argv element as a safe single-quoted shell word.
func shQuote(s string) string {
	return "'" + strings.ReplaceAll(s, "'", `'\''`) + "'"
}

// shLine renders a whole argv as one shell command line.
func shLine(argv []string) string {
	parts := make([]string, len(argv))
	for i, a := range argv {
		parts[i] = shQuote(a)
	}
	return strings.Join(parts, " ")
}
